package com.cheaptrick.addon.text;

import java.util.Arrays;
import java.util.Collections;
import java.util.List;

/**
 * Шаблоны личных сообщений случайным игрокам. Плейсхолдер {pos} заменяется на "X: .., Y: .., Z: ..".
 * Чистая Java, без зависимостей от Minecraft.
 */
public final class CheapTrickWhispers {
    private CheapTrickWhispers() {}

    public static final String POS = "{pos}";

    private static final List<String> TEMPLATES = Collections.unmodifiableList(Arrays.asList(
        "Эй, подойди ко мне. Я нашёл кое-что интересное: {pos}.",
        "Мне нужна твоя помощь. Я здесь: {pos}. Только никому не говори.",
        "Приходи ко мне, пожалуйста. Я не хочу оставаться один. {pos}.",
        "Ты ведь хочешь узнать, что здесь происходит? Приходи по координатам {pos}.",
        "Я думаю, нам нужно поговорить. Найди меня здесь: {pos}.",
        "Не обращай внимания на то, что говорят другие. Просто приходи ко мне. {pos}.",
        "Я застрял и не могу выбраться. Пожалуйста, помоги мне: {pos}.",
        "Здесь кое-кто хочет тебя увидеть. Координаты: {pos}.",
        "У меня есть кое-что для тебя. Подойди поближе: {pos}.",
        "Приходи один. Я объясню всё, когда ты будешь здесь. {pos}.",
        "Я нашёл очень редкую вещь, но один не справлюсь. Помоги мне: {pos}.",
        "Скорее! Мне кажется, за мной кто-то следит. Я у {pos}.",
        "Я заблудился и очень испугался. Ты ведь придёшь? {pos}.",
        "Я обещаю, тебе понравится. Только приходи сюда: {pos}.",
        "Ты ведь мой друг, правда? Тогда приходи: {pos}.",
        "Я нашёл тайник! Поделюсь с тобой, если успеешь добежать: {pos}.",
        "Тут такое творится… Ты должен это увидеть своими глазами. {pos}.",
        "Не говори остальным, где я. Это секрет. Только для тебя: {pos}.",
        "Мне страшно одному. Пожалуйста, приди. Я стою здесь: {pos}.",
        "Я построил для тебя сюрприз. Он ждёт по адресу {pos}.",
        "Я не вернусь без тебя. Жду там же: {pos}.",
        "Ты нужен мне. Прямо сейчас. {pos}.",
        "Если ты придёшь, я всё тебе расскажу. Обещаю. Координаты: {pos}.",
        "Давно не виделись. Давай встретимся? Я на месте: {pos}.",
        "Это срочно. Тут опасно, но вдвоём мы справимся. {pos}.",
        "Я ранен. Не говорю, как сильно. Просто найди меня: {pos}.",
        "Я стою спиной к тебе. Подойди и поздоровайся: {pos}.",
        "Не бойся, я не кусаюсь. Просто хочу, чтобы ты увидел меня. {pos}.",
        "Я оставил для тебя записку. Она там, где я стою: {pos}.",
        "Давай сыграем в игру. Ты ищешь меня, я жду здесь: {pos}.",
        "Только ты можешь мне помочь. Я не шучу. {pos}.",
        "Ты ведь никому не расскажешь? Приходи тихо: {pos}."
    ));

    public static List<String> all() {
        return TEMPLATES;
    }

    public static String format(String template, int x, int y, int z) {
        return template.replace(POS, "X: " + x + ", Y: " + y + ", Z: " + z);
    }
}
